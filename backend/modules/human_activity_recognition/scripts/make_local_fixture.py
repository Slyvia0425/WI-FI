#!/usr/bin/env python3
"""Generate a tiny deterministic csi-bench-shaped fixture for offline Module B development."""

from __future__ import annotations

import csv
import json
from pathlib import Path

import h5py
import numpy as np

ROOT = Path(__file__).resolve().parents[4]
FIXTURE = ROOT / "backend/modules/human_activity_recognition/fixtures/mini_csi_bench"
TASK = FIXTURE / "Multitask/HumanActivityRecognition"
SAMPLES = FIXTURE / "Multitask/sub_Human_h5"
CLASSES = ("standing", "sitting", "walking", "lying")


def main() -> int:
    (TASK / "metadata").mkdir(parents=True, exist_ok=True)
    (TASK / "splits").mkdir(parents=True, exist_ok=True)
    SAMPLES.mkdir(parents=True, exist_ok=True)
    (TASK / "metadata/label_mapping.json").write_text(
        json.dumps({str(index): label for index, label in enumerate(CLASSES)}, indent=2) + "\n",
        encoding="utf-8",
    )
    rng = np.random.default_rng(20261017)
    rows: list[dict[str, str]] = []
    splits: dict[str, list[str]] = {"train": [], "val": [], "test": []}
    for class_id, label in enumerate(CLASSES):
        for index in range(4):
            sample_id = f"{label}-{index:02d}"
            split = "train" if index < 2 else "val" if index == 2 else "test"
            signal = rng.normal(0.0, 0.03, size=(232, 24)).astype(np.float32)
            signal[class_id * 8 : class_id * 8 + 8] += np.sin(np.linspace(0, 4 * np.pi, 24, dtype=np.float32)) * (
                class_id + 1
            )
            with h5py.File(SAMPLES / f"{sample_id}.h5", "w") as handle:
                handle.create_dataset("CSI_amps", data=signal)
            splits[split].append(sample_id)
            rows.append(
                {
                    "sample_id": sample_id,
                    "path": f"../../sub_Human_h5/{sample_id}.h5",
                    "activity": label,
                    "session_id": f"session-{sample_id}",
                    "user_id": f"user-{sample_id}",
                    "environment_id": f"env-{sample_id}",
                    "device_id": f"fixture-device-{sample_id}",
                }
            )
    with (TASK / "metadata/sample_metadata.csv").open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    for split, ids in splits.items():
        (TASK / f"splits/{split}_id.json").write_text(json.dumps(ids, indent=2) + "\n", encoding="utf-8")
    (FIXTURE / "fixture_manifest.json").write_text(
        json.dumps(
            {
                "synthetic": True,
                "source": "generated by make_local_fixture.py",
                "feature_size": 232,
                "frames": 24,
                "classes": list(CLASSES),
                "samples": len(rows),
                "splits": {key: len(value) for key, value in splits.items()},
            },
            indent=2,
        )
        + "\n",
        encoding="utf-8",
    )
    print(FIXTURE)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
