export function reviewText(value, language = 'en') {
  if (language !== 'zh' || typeof value !== 'string') return value
  const trimmed = value.trim()
  if (Object.hasOwn(zh, trimmed)) return value.replace(trimmed, zh[trimmed])
  return value
    .replace(/^Thirty-second standardized CSI amplitude summary( and respiratory sensor reference)?; not reconstructed respiration$/, (_, ref) => `30 秒标准化 CSI 幅度概览${ref ? '及呼吸传感器参考波形' : ''}；并非重建呼吸波形`)
    .replace(/^Latest complete ([\d.]+)–([\d.]+)s window$/, '最近一个完整窗口：$1–$2 秒')
    .replace(/^([\d.]+)–([\d.]+)s window · (.+)$/, (_, a, b, reason) => `${a}–${b} 秒窗口 · ${reviewReason(reason)}`)
    .replace(/BPM · experimental/g, '次/分钟 · 实验性')
    .replace(/Subject(\d+)/g, '受试者$1').replace(/Room(\d+)/g, '房间$1')
    .replace(/\b(Quiet|Interference|Foetus|Yearner|Sitting|Log|Soldier)\b/g, word => zh[word])
}

function reviewReason(reason) {
  return reason.replace('model evidence', '模型证据').replace('timestamp gap', '采样时间缺口')
    .replace('insufficient data', '数据不足').replace('invalid signal or score', '无效信号或分数')
    .replace('BPM (experimental)', '次/分钟（实验性）')
}

// Transform React elements, never mutate the DOM or translate data/IDs/classes.
// Component state and event handlers are preserved across a language switch.
export function localizeTree(node, language = 'en') {
  if (language !== 'zh') return node
  if (Array.isArray(node)) return node.map(child => localizeTree(child, language))
  if (typeof node === 'string') return reviewText(node, language)
  if (!isValidElement(node)) return node
  if (node.type === 'code' || node.props['data-review-language'] === 'skip') return node
  const props = {}
  for (const key of ['aria-label', 'title', 'placeholder', 'label', 'detail', 'unit']) {
    if (typeof node.props[key] === 'string') props[key] = reviewText(node.props[key], language)
  }
  if (node.props.children !== undefined) props.children = localizeTree(node.props.children, language)
  return cloneElement(node, props)
}
